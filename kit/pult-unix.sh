#!/bin/sh
# Пульт (macOS/Linux): открывает ВСЕ аккаунты из папки akkaunty сразу, каждый
# своим окном. У каждого своя папка данных и свой ключ (отдельный вход), поэтому
# окна не дерутся и аккаунты друг друга не выкидывают.
set -e
cd "$(dirname "$0")"

# macOS вешает «карантин» на скачанное и блокирует запуск. Снимаем со всей папки
# (первый раз сам пульт надо открыть в обход — см. ЧИТАЙ-МЕНЯ).
[ "$(uname -s)" = "Darwin" ] && xattr -dr com.apple.quarantine "$PWD" 2>/dev/null || true

base="$PWD/akkaunty"
[ -d "$base" ] || { printf '\nНет папки «akkaunty» рядом с этим файлом.\n\n'; exit 1; }

# имя пускача в подпапке зависит от ОС
launcher="Открыть аккаунт.command"
[ "$(uname -s)" = "Darwin" ] || launcher="открыть-аккаунт.sh"

n=0
for d in "$base"/*/; do
  [ -f "$d$launcher" ] || continue
  # каждый аккаунт — своим пускачом, в фоне и отвязанно: так все открываются
  # разом, а это окно можно закрыть, Telegram-ы останутся жить.
  ( cd "$d" && nohup sh "$launcher" >/dev/null 2>&1 & ) || true
  n=$((n + 1))
  sleep 2
done

printf '\nОткрыл аккаунтов: %s. Окна Telegram появятся через пару секунд — у каждого своё.\n' "$n"
printf 'Если у какого-то сеть не поднялась — включи VPN и запусти снова.\n'
printf 'Это окно можно закрыть, аккаунты останутся открытыми.\n\n'
