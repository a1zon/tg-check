_ROOM_MAP = [
    (_rx(r"студи"), "студия"),
    (_rx(r"(одно\s*комнат|однушк|\b1\s*-?\s*к)"), "1-комнатная"),
    (_rx(r"(двух\s*комнат|двушк|евродвушк|\b2\s*-?\s*к)"), "2-комнатная"),
    (_rx(r"(тр[её]х\s*комнат|тр[её]шк|евротр[её]шк|\b3\s*-?\s*к)"), "3-комнатная"),
]
_RE_NEW = _rx(r"(новостройк|новострой|от\s+застройщик|дду|котлован)")
_RE_SEC = _rx(r"(вторичк|вторичн|вторичное)")
_RE_ZHKNAME = _rx(r"жк\s+«?([a-zа-я0-9\- ]{2,20})»?")
_RE_BUDGET = _rx(r"(до\s*)?(\d{1,2}[.,]?\d?)\s*млн")
_RE_FAM_MOVE = _rx(r"(семейн\w*\s+ипотек)")
_RE_MORTG = _rx(r"ипотек")
_RE_MATK = _rx(r"(маткапитал|материнск\w*\s+капитал|мат\.?\s*капитал)")
_RE_SELLOWN = _rx(r"продаём?\s+(?:свою|кварт)")
_RE_CASH = _rx(r"наличн")


def _extract(t):
    f = {}
    for rx, label in _ROOM_MAP:
        if rx.search(t):
            f["rooms"] = label
            break
    if _RE_NEW.search(t):
        f["type"] = "новостройка"
    elif _RE_SEC.search(t):
        f["type"] = "вторичка"
    for d in DISTRICTS:
        if d in t:
            f["district"] = DISTRICT_DISPLAY.get(d, d.title())
            break
    mz = _RE_ZHKNAME.search(t)
    if mz:
        f["zhk"] = "ЖК " + mz.group(1).strip().title()
    mb = _RE_BUDGET.search(t)
    if mb:
        f["budget"] = f"{'до ' if mb.group(1) else ''}{mb.group(2).replace(',', '.')} млн"
    mt = RE_TIME.search(t)
    if mt:
        f["timeline"] = mt.group(0).strip()
    fin = []
    if _RE_FAM_MOVE.search(t):
        fin.append("семейная ипотека")
    elif _RE_MORTG.search(t):
        fin.append("ипотека")
    if _RE_MATK.search(t):
        fin.append("маткапитал")
    if _RE_SELLOWN.search(t):
        fin.append("продажа своей")
    if _RE_CASH.search(t):
        fin.append("наличные")
    if fin:
        f["financing"] = ", ".join(fin)
    mp = RE_PAIN.search(t)
    if mp:
        f["pain"] = mp.group(0).strip()
    return f


