def _has(rx, t):
    return bool(rx.search(t))


def classify(text, reply=None):
    """
    Категория одного сообщения. Возвращает словарь:
      category HOT|WARM|COLD|SKIP, score 0-100, reason, tags, fields.
    reply — текст сообщения, на которое отвечают (контекст треда), можно None.
    """
    t = _norm(text)
    ctx = (t + " " + _norm(reply)).strip()
    tags = []

    about_flat = _has(RE_APART_WORD, ctx) or any(d in ctx for d in DISTRICTS)

    # --- жёсткие отсечки ---
    if _has(RE_AGENT, t) or (_has(RE_LINK, t) and _has(RE_SELL, t)):
        tags.append("agent")
        return _res("SKIP", 0, "похоже на риелтора/рекламу — не пишем", tags, {})

    # про другой город (СПб/Москва/…) и без Екатеринбурга — не наш
    if _has(RE_OTHER_CITY, ctx) and not _has(RE_EKB, ctx):
        tags.append("other_city")
        return _res("SKIP", 0, "про другой город, не Екатеринбург", tags, {})

    if _has(RE_RENT, t) and not _has(RE_BUY_STRONG, t):
        tags.append("rent")
        return _res("SKIP", 0, "про аренду, а не покупку", tags, {})

    if _has(RE_SELL, t) and not (_has(RE_ACTION, t) or _has(RE_FIN, t) or _has(RE_HELP, t)):
        # паркинг/мебель/машиноместо — мимо; квартиру — это продавец-лид
        if _has(RE_JUNK, t) and not _has(RE_FLAT, t):
            return _res("SKIP", 0, "продаёт паркинг/вещи, не квартиру", tags, {})
        if _has(RE_FLAT, t) and SELLERS_AS_LEADS:
            tags.append("seller")
            return _res("WARM", 50, "продаёт квартиру — клиент на реализацию",
                        tags, _extract(ctx))
        return _res("SKIP", 0, "продаёт, а нас интересует покупка", tags, {})

    if _has(RE_OTHER, t) and not about_flat:
        tags.append("other_type")
        return _res("SKIP", 0, "дом/участок/коммерция — не квартира", tags, {})

    if _has(RE_DONE, t):
        return _res("COLD", 12, "речь об уже совершённой покупке / отказе", tags, _extract(ctx))

    # обсуждение/мнение (слышал, говорят, схемы, наказывают…) без первого лица
    # и без одобренных финансов — это болтовня, а не запрос на покупку
    if _has(RE_TALK, ctx) and not _has(RE_ACTION, ctx) and not _has(RE_FIN_STRONG, ctx) \
            and not _rx(r"купить|куплю|планиру\w+\s+куп").search(ctx):
        return _res("COLD", 8, "обсуждение/мнение, не запрос на покупку", tags, {})

    # разговор не про жильё вообще — холодно, что бы там ни было за глаголы
    if not about_flat:
        return _res("COLD", 5, "не про покупку жилья", tags, _extract(ctx))

    # --- признаки покупки ---
    sig = {
        "action": _has(RE_ACTION, ctx),
        "concrete": _has(RE_ROOMS, ctx) or _has(RE_MONEY, ctx) or _has(RE_METR, ctx)
                    or _has(RE_ZHK, ctx) or any(d in ctx for d in DISTRICTS),
        "time": _has(RE_TIME, ctx),
        "fin": _has(RE_FIN, ctx),
        "help": _has(RE_HELP, ctx),
        "pain": _has(RE_PAIN, ctx),
    }
    n = sum(1 for v in sig.values() if v)
    fields = _extract(ctx)
    warm_marker = _has(RE_WARM, ctx)
    strong_hot = sig["fin"] or sig["time"] or sig["help"]

    # «копим / присматриваемся / думаем» — явный маркер «ещё не готов».
    # Опускаем в WARM, ЕСЛИ нет сильного сигнала (финансы/срок/запрос помощи).
    if warm_marker and not (sig["fin"] or sig["help"]):
        score = 48 if sig["concrete"] else 42
        return _res("WARM", score, "интерес есть, но решение не принято", tags, fields)

    # HOT: минимум 2 признака, один из которых — действие / помощь / финансы
    strong = sig["action"] or sig["help"] or sig["fin"]
    if n >= 2 and strong:
        score = 60
        score += 12 if sig["concrete"] else 0
        score += 12 if sig["time"] else 0
        score += 14 if sig["fin"] else 0
        score += 6 if sig["help"] else 0
        score += 4 if sig["pain"] else 0
        score = min(100, score)
        why = ", ".join(k for k, v in sig.items() if v)
        return _res("HOT", score, f"признаки покупки: {why}", tags, fields)

    # WARM: один сигнал действия/помощи, либо вялый интерес
    if warm_marker or sig["action"] or sig["help"] or sig["pain"] or (_has(RE_FIN_STRONG, ctx) and not sig["concrete"]):
        score = 45 + (8 if sig["concrete"] else 0) + (6 if sig["fin"] else 0)
        return _res("WARM", min(59, score), "интерес есть, но без срока/конкретики", tags, fields)

    # только конкретика без намерения (обсуждение цен/районов) → холодно
    return _res("COLD", 20, "общее обсуждение темы", tags, fields)


def _res(category, score, reason, tags, fields):
    return {"category": category, "score": int(score), "reason": reason,
            "tags": tags, "fields": fields}


