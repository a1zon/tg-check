def fill_template(tpl, p, link=""):
    """
    Подставляет данные лида в свой шаблон. Плейсхолдеры (рус/англ):
      {чат}/{chat}   — чат, где нашли
      {запрос}/{request} — что подбирает (краткая перефразировка запроса)
      {бюджет}/{budget}, {срок}, {имя}/{name}, {LINK}/{ссылка}
    Spinttax {а|б} разворачивать должен вызывающий (у панели свой spin).
    """
    first = (str(p.get("display_name") or "").split(" ") or [""])[0]
    req = p.get("what_looking_for") or "квартиру"
    repl = {
        "{чат}": p.get("found_chat") or "", "{chat}": p.get("found_chat") or "",
        "{запрос}": req, "{request}": req,
        "{бюджет}": p.get("budget") or "", "{budget}": p.get("budget") or "",
        "{срок}": p.get("timeline") or "", "{имя}": first, "{name}": first,
        "{LINK}": link, "{ссылка}": link,
    }
    out = str(tpl or "")
    for k, v in repl.items():
        out = out.replace(k, v)
    # подчистить двойные пробелы/пустые скобки, если поля пустые
    out = re.sub(r"\(\s*\)", "", out)
    out = re.sub(r"[ \t]+", " ", out)
    return out.strip()
