def _useful_line(p):
    fin = (p.get("financing") or "").lower()
    typ = (p.get("what_looking_for") or "").lower()
    if "семейн" in fin or "маткапитал" in fin:
        return ("Если подходите под семейную ипотеку или маткапитал — это заметно "
                "снижает первый взнос; подскажу, как сложить их вместе.")
    if "продажа своей" in fin:
        return ("Когда продаёшь свою и сразу покупаешь — важно состыковать сделки по "
                "срокам, чтобы не остаться без жилья между ними; помогаю это развести.")
    if "ипотек" in fin:
        return ("По ипотеке сейчас многое зависит от программы и застройщика — "
                "подскажу, где по вашему бюджету условия адекватнее.")
    if "новостройк" in typ:
        return ("По новостройкам разница не в цене, а в застройщике и сроках сдачи — "
                "подскажу, у кого в вашем районе со сдачей без сюрпризов.")
    if "вторичк" in typ:
        return ("На вторичке главное — юридическая чистота и торг; помогу проверить "
                "объект и не переплатить.")
    return ("Подскажу по районам и вариантам под ваш бюджет — где сейчас адекватная "
            "цена и на что смотреть.")


def _looking_phrase(p):
    """Читаемая фраза запроса: «2-комнатную в районе Академический»."""
    rooms = p.get("rooms")
    base = ROOMS_ACC.get(rooms, rooms) if rooms else "квартиру"
    zhk, dist, typ = p.get("zhk"), p.get("district"), p.get("type")
    if zhk:
        base += f" в {zhk}"
    else:
        if typ == "новостройка":
            base += " в новостройке"
        elif typ == "вторичка":
            base += " на вторичке"
        if dist == "центр":
            base += " в центре"
        elif dist == "ВИЗ":
            base += " на ВИЗе"
        elif dist:
            base += f" в районе {dist}"
    return base


def _hook(p):
    chat = p.get("found_chat") or (p.get("source_chats") or [""])[0]
    look = p.get("what_looking_for")
    budget = p.get("budget")
    if look and budget:
        tail = f", что вы подбираете {look} (бюджет {budget})"
    elif look:
        tail = f", что вы подбираете {look}"
    elif budget:
        tail = f", что присматриваете квартиру за {budget}"
    else:
        tail = ", что вы в поиске квартиры"
    where = f"в чате «{chat}»" if chat else "в чате"
    return f"Здравствуйте! Увидел {where}{tail}."


def generate_outreach(profile, landing_url=""):
    """
    Первое личное сообщение, 2 варианта. A — со ссылкой на квиз, B — с вопросом.
    Строится из карточки: зацепка (чат + запрос) → польза → кто я → мягкий шаг.
    """
    p = profile

    # продавцу квартиры — другое письмо: помощь с реализацией + покупка взамен
    if p.get("seller"):
        chat = p.get("found_chat") or (p.get("source_chats") or [""])[0]
        where = f"в чате «{chat}»" if chat else "в чате"
        s_hook = f"Здравствуйте! Увидел {where}, что вы продаёте квартиру."
        s_useful = ("Помогу продать быстрее и по адекватной цене, а если планируете покупку "
                    "взамен — подберу вариант и состыкую сделки, чтобы не остаться между ними.")
        s_who = "Я Егор, брокер в «Этажах», занимаюсь и продажей, и покупкой в Екатеринбурге."
        link = (landing_url or "").strip()
        s_a = (f"Если удобно — пришлю бесплатную оценку вашей квартиры и план продажи: {link}"
               if link else "Если удобно — пришлю бесплатную оценку вашей квартиры и план продажи.")
        s_b = "Подскажите, какую квартиру продаёте и в какие сроки хотите выйти на сделку?"
        return {"variant_a": _clean("\n".join([s_hook, s_useful, s_who, s_a])),
                "variant_b": _clean("\n".join([s_hook, s_useful, s_who, s_b]))}

    hook = _hook(p)
    useful = _useful_line(p)
    who = "Я Егор, брокер в «Этажах», как раз помогаю семьям с покупкой в Екатеринбурге."

    link = (landing_url or "").strip()
    if link:
        cta_a = f"Если удобно — соберите за минуту короткий запрос, и я пришлю подборку под вас: {link}"
    else:
        cta_a = "Если удобно — пришлю подборку под ваш запрос, скажите только, куда смотреть."

    if p.get("timeline"):
        q = "Подскажите, в какие сроки планируете — покажу только то, что реально успеть."
    elif p.get("budget"):
        q = "Какой район рассматриваете в первую очередь? Подберу пару вариантов под бюджет."
    else:
        q = "Подскажите, какой район и бюджет рассматриваете — подберу пару вариантов."

    return {"variant_a": _clean("\n".join([hook, useful, who, cta_a])),
            "variant_b": _clean("\n".join([hook, useful, who, q]))}


def _clean(s):
    s = re.sub(r"[ \t]+", " ", s)
    return s.strip()


