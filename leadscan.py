_RANK = {"skip": 0, "cold": 1, "warm": 2, "hot": 3, "closed": 4}


def update_profile(profiles, msg, cls):
    """
    Кладёт/обновляет карточку юзера в словаре profiles (user_id -> карточка).
    msg — словарь сообщения: user_id, username, display_name, chat, message_id,
    date, text, by. cls — результат classify(). Возвращает обновлённую карточку.
    """
    uid = str(msg.get("user_id") or "")
    if not uid:
        return None
    # ник как у агентства/риелтора — не наш лид, помечаем и не ведём карточку
    if RE_AGENT_NAME.search(_norm(msg.get("display_name")) + " " + _norm(msg.get("username"))):
        pe = profiles.get(uid)
        if pe:
            pe["status"] = "skip"; pe["agent"] = True
        return pe
    cat = cls["category"]
    p = profiles.get(uid)
    if p is None:
        p = {
            "user_id": uid, "username": msg.get("username") or "",
            "display_name": msg.get("display_name") or "",
            "status": cat.lower(), "score": cls["score"],
            "rooms": None, "type": None, "district": None, "zhk": None,
            "what_looking_for": None, "budget": None, "timeline": None,
            "financing": None, "family_context": None, "pain_point": None,
            "source_chats": [], "found_chat": msg.get("chat") or "",
            "by": msg.get("by") or "", "evidence": [],
            "first_seen": msg.get("date") or "", "last_seen": msg.get("date") or "",
            "message_sent": False, "outreach": None,
        }
        profiles[uid] = p

    if msg.get("username"):
        p["username"] = msg["username"]
    if msg.get("display_name"):
        p["display_name"] = msg["display_name"]
    if msg.get("by"):
        p["by"] = msg["by"]

    if "seller" in (cls.get("tags") or []):
        p["seller"] = True
    if _has(RE_DONE, _norm(msg.get("text"))):
        p["status"] = "closed"
    elif _RANK.get(cat.lower(), 0) > _RANK.get(p["status"], 0):
        p["status"] = cat.lower()
    p["score"] = max(int(p.get("score") or 0), cls["score"])

    fld = cls["fields"]
    for k in ("rooms", "type", "district", "zhk"):
        if fld.get(k) and not p.get(k):
            p[k] = fld[k]
    if any(p.get(k) for k in ("rooms", "type", "district", "zhk")):
        p["what_looking_for"] = _looking_phrase(p)
    for k_src, k_dst in [("budget", "budget"), ("timeline", "timeline"),
                         ("financing", "financing"), ("pain", "pain_point")]:
        if fld.get(k_src) and not p.get(k_dst):
            p[k_dst] = fld[k_src]

    chat = msg.get("chat") or ""
    if chat and chat not in p["source_chats"]:
        p["source_chats"].append(chat)
    if chat and cat in ("HOT", "WARM"):
        p["found_chat"] = chat

    if cat in ("HOT", "WARM") and msg.get("text"):
        ev = {"message_id": str(msg.get("message_id") or ""),
              "chat": chat, "quote": str(msg["text"])[:160]}
        if ev not in p["evidence"]:
            p["evidence"].append(ev)
            p["evidence"] = p["evidence"][-6:]

    if msg.get("date"):
        p["last_seen"] = msg["date"]
        if not p.get("first_seen"):
            p["first_seen"] = msg["date"]
    return p


